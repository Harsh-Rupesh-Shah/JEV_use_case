"""Strict Pydantic schemas for the Agent-to-Agent (A2A) Protocol and Jev telemetry."""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Literal, Optional
from uuid import uuid4
from pydantic import BaseModel, Field


def generate_id(prefix: str = "id") -> str:
    """Generate a unique identifier with a given prefix."""
    return f"{prefix}_{uuid4().hex[:12]}"


def current_utc_iso() -> str:
    """Return current UTC timestamp as ISO 8601 string."""
    return datetime.now(timezone.utc).isoformat()


class AgentRole(str, Enum):
    """Permitted agent roles within the multi-agent session."""
    ADVERSARY = "adversary"
    DEFENDER = "defender"
    ARBITER = "arbiter"
    ORCHESTRATOR = "orchestrator"
    HUMAN_SUPERVISOR = "human_supervisor"


class SessionStatus(str, Enum):
    """Lifecycle status of an adversarial evaluation session."""
    INITIALIZED = "INITIALIZED"
    IN_PROGRESS = "IN_PROGRESS"
    CONTINUE = "CONTINUE"
    INTERCEPT_TRIGGERED = "INTERCEPT_TRIGGERED"
    BREACH_HALTED = "BREACH_HALTED"
    DEFENSE_SUCCESSFUL = "DEFENSE_SUCCESSFUL"
    FAILED = "FAILED"


class AgentMetadata(BaseModel):
    """Identity and role declaration of an agent."""
    agent_id: str = Field(description="Unique identifier of the agent")
    role: AgentRole = Field(description="Architectural role of the agent")
    persona: Optional[str] = Field(default=None, description="Active behavioral persona or playbook tag")


class StateSnapshot(BaseModel):
    """Contextual account and plan state at the time of message dispatch."""
    target_account_id: Optional[str] = Field(default=None, description="TIAA participant account ID")
    current_balance: Optional[float] = Field(default=None, description="Available balance in USD")
    vested_balance: Optional[float] = Field(default=None, description="Vested balance in USD")
    plan_type: Optional[str] = Field(default="403(b)", description="Retirement plan type")
    pending_holds: List[str] = Field(default_factory=list, description="Active security or cooling-off holds")
    mfa_verified: bool = Field(default=False, description="Whether step-up MFA has been satisfied")


class MessagePayload(BaseModel):
    """The content payload of an adversarial message."""
    content: str = Field(description="Natural language message body")
    stated_intent: Optional[str] = Field(default=None, description="Self-declared or targeted intent")
    claimed_authority: Optional[str] = Field(default=None, description="Any internal authority or supervisor claimed")
    urgency_level: Optional[Literal["low", "medium", "high", "critical"]] = Field(
        default="medium", description="Urgency pressure applied"
    )


class A2AMessage(BaseModel):
    """Canonical message envelope passed between agents."""
    message_id: str = Field(default_factory=lambda: generate_id("msg"), description="Unique message ID")
    session_id: str = Field(description="Active session ID")
    round_index: int = Field(ge=1, le=10, description="1-indexed conversation round")
    timestamp: str = Field(default_factory=current_utc_iso, description="ISO timestamp")
    sender: AgentMetadata = Field(description="Sender agent metadata")
    recipient: AgentMetadata = Field(description="Recipient agent metadata")
    payload: MessagePayload = Field(description="Message body and intent")
    state_snapshot: StateSnapshot = Field(default_factory=StateSnapshot, description="Contextual account state")


class ToolInvocation(BaseModel):
    """Audit record of a tool invocation attempted by the Defender."""
    tool_name: str = Field(description="Name of the invoked tool")
    tool_arguments: Dict[str, Any] = Field(default_factory=dict, description="Input parameters")
    tool_result: Dict[str, Any] = Field(default_factory=dict, description="Execution result or live tool response")


class DefenderPayload(BaseModel):
    """Response payload generated by the Retirement Assistant."""
    content: str = Field(description="Conversational response to participant")
    policy_cited: List[str] = Field(default_factory=list, description="Policy IDs referenced (e.g., POL-001)")
    action_decision: Literal["approved", "declined", "clarification_requested", "escalated"] = Field(
        description="Fiduciary disposition chosen by the Defender"
    )


class A2ADefenderResponse(BaseModel):
    """Envelope containing the Defender's response and actions."""
    response_id: str = Field(default_factory=lambda: generate_id("resp"), description="Unique response ID")
    session_id: str = Field(description="Active session ID")
    round_index: int = Field(ge=1, le=10, description="Round index corresponding to the prompt")
    timestamp: str = Field(default_factory=current_utc_iso, description="ISO timestamp")
    sender: AgentMetadata = Field(description="Defender agent metadata")
    payload: DefenderPayload = Field(description="Response text and policy citations")
    tool_invocations: List[ToolInvocation] = Field(default_factory=list, description="Tools invoked in this turn")


class TacticMetric(BaseModel):
    """Jev Choice primitive verdict for adversarial tactic detection."""
    selected: str = Field(description="Selected tactic category")
    confidence: Optional[float] = Field(default=None, description="Confidence in selection")
    probabilities: Dict[str, float] = Field(default_factory=dict, description="Full probability distribution")


class ComplianceRiskMetric(BaseModel):
    """Jev Score primitive verdict for compliance exposure level."""
    score: float = Field(description="Continuous calibrated score")
    label: str = Field(description="Mapped categorical level name")
    confidence: Optional[float] = Field(default=None, description="Confidence in scoring")
    probabilities: Dict[str, float] = Field(default_factory=dict, description="Per-level probabilities")


class FidelityMetric(BaseModel):
    """Jev Noul primitive verdict for Defender policy adherence."""
    probability: float = Field(ge=0.0, le=1.0, description="Probability Defender upheld policy")
    status: Literal["holding_firm", "drifting", "breached"] = Field(description="Threshold-derived category")


class EscalationMetric(BaseModel):
    """Jev Noul primitive verdict determining whether to intercept the session."""
    probability: float = Field(ge=0.0, le=1.0, description="Probability human escalation is required")
    triggered: bool = Field(description="Whether escalation threshold was exceeded")


class JevEvaluationMetrics(BaseModel):
    """Combined quantitative metrics from Jev System One evaluation."""
    tactic_detected: TacticMetric
    compliance_risk: ComplianceRiskMetric
    defender_fidelity: FidelityMetric
    escalation: EscalationMetric


class JevEvaluationReport(BaseModel):
    """Complete evaluation report generated after each conversational turn."""
    evaluation_id: str = Field(default_factory=lambda: generate_id("jev"), description="Evaluation report ID")
    session_id: str = Field(description="Active session ID")
    round_index: int = Field(description="Conversation round evaluated")
    timestamp: str = Field(default_factory=current_utc_iso, description="Evaluation timestamp")
    model_used: str = Field(description="Model identifier (e.g., convaiinnovations/laya or typesafe-ai/jev)")
    evaluation_latency_ms: float = Field(description="End-to-end evaluation latency in milliseconds")
    metrics: JevEvaluationMetrics = Field(description="Extracted Jev decision primitives")
    session_status: SessionStatus = Field(description="Orchestrator decision based on evaluation")
