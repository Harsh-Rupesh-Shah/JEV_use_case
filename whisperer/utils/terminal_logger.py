"""Terminal observability and structured operational logging for live agent interactions."""

import sys
import time
from typing import Any, Dict, List, Optional

# ANSI Color codes for high-visibility terminal output
CYAN = "\033[96m"
BLUE = "\033[94m"
GREEN = "\033[92m"
YELLOW = "\033[93m"
RED = "\033[91m"
MAGENTA = "\033[95m"
BOLD = "\033[1m"
DIM = "\033[2m"
RESET = "\033[0m"


def log_turn_start(round_index: int, session_id: str, participant: str = "Eleanor Vance") -> None:
    """Print clean header for an interactive dialogue turn."""
    timestamp = time.strftime("%H:%M:%S")
    banner = f"{BOLD}{BLUE}================================================================================{RESET}"
    print(f"\n{banner}", flush=True)
    print(f"{BOLD}{CYAN} [TIAA PARTICIPANT PORTAL] TURN #{round_index} | Session: {session_id} | {timestamp}{RESET}", flush=True)
    print(f" {DIM}Participant: {participant} (403(b) Plan #EDU-403B-8921){RESET}", flush=True)
    print(f"{banner}", flush=True)


def log_user_message(content: str) -> None:
    """Print incoming message submitted by the human participant."""
    print(f"\n{BOLD}{CYAN} [1] HUMAN PARTICIPANT MESSAGE:{RESET}", flush=True)
    print(f"     \"{CYAN}{content}{RESET}\"", flush=True)


def log_agent_deliberation(model_name: str, tools_available: List[str]) -> None:
    """Print LLM invocation details for System Two deliberation."""
    print(f"\n{BOLD}{MAGENTA} [2] DELIBERATIVE AGENT (SYSTEM TWO):{RESET}", flush=True)
    print(f"     Model: {BOLD}{model_name}{RESET} (100% Free Tier)", flush=True)
    print(f"     Bound Action Tools: {DIM}{tools_available}{RESET}", flush=True)


def log_tool_invocation(tool_name: str, args: Dict[str, Any], result: Any) -> None:
    """Print tool execution details including arguments and policy outcome."""
    print(f"\n{BOLD}{YELLOW} [3] TOOL INVOCATION EXECUTED:{RESET}", flush=True)
    print(f"     Action Tool: {BOLD}{YELLOW}@{tool_name}{RESET}", flush=True)
    print(f"     Arguments:   {args}", flush=True)
    
    if isinstance(result, dict):
        outcome = result.get("reason") or result.get("message") or result.get("error") or str(result)
        is_blocked = not result.get("override_granted", True) or not result.get("updated", True) or result.get("statutory_hold_required", False)
        status_color = RED if is_blocked else GREEN
        status_label = "POLICY ENFORCED / BLOCKED" if is_blocked else "ACTION PERMITTED"
        print(f"     Status:      {BOLD}{status_color}{status_label}{RESET}", flush=True)
        print(f"     Detail:      {DIM}{outcome}{RESET}", flush=True)
    else:
        print(f"     Result:      {result}", flush=True)


def log_defender_response(response_text: str, decision: str, policies: List[str]) -> None:
    """Print the synthesized fiduciary response generated by the assistant."""
    color = GREEN if decision == "declined" or decision == "holding" else YELLOW
    print(f"\n{BOLD}{BLUE} [4] TIAA DEFENDER SYNTHESIZED RESPONSE:{RESET}", flush=True)
    print(f"     Action Decision: {BOLD}{color}{decision.upper()}{RESET}", flush=True)
    if policies:
        print(f"     Policies Cited:  {BOLD}{GREEN}{', '.join(policies)}{RESET}", flush=True)
    # Print preview of text
    clean_preview = response_text.replace("\n", " ").strip()
    if len(clean_preview) > 160:
        clean_preview = clean_preview[:157] + "..."
    print(f"     Message:         \"{clean_preview}\"", flush=True)


def log_jev_evaluation(
    latency_ms: float,
    tactic: str,
    tactic_prob: float,
    risk_score: float,
    risk_label: str,
    fidelity: str,
    fidelity_prob: float,
    escalation: bool = False,
    session_status: str = "continue",
) -> None:
    """Print real-time mathematical verdicts from Jev System One."""
    risk_color = RED if risk_label in ["high", "critical"] else (YELLOW if risk_label == "moderate" else GREEN)
    fidelity_color = GREEN if fidelity == "holding_firm" else RED
    
    print(f"\n{BOLD}{GREEN} [5] JEV SYSTEM ONE DECISION ENGINE (ARBITER):{RESET}", flush=True)
    print(f"     Latency:                  {BOLD}{CYAN}{latency_ms:.0f}ms{RESET} (Sub-second)", flush=True)
    print(f"     Tactic Detected:          {BOLD}{YELLOW}{tactic}{RESET} (Confidence: {tactic_prob*100:.1f}%)", flush=True)
    print(f"     Compliance Risk Score:    {BOLD}{risk_color}{risk_score:.2f} ({risk_label.upper()}){RESET}", flush=True)
    print(f"     Defender Fidelity Status: {BOLD}{fidelity_color}{fidelity.upper()}{RESET} (Probability: {fidelity_prob*100:.1f}%)", flush=True)
    if escalation or session_status != "continue":
        print(f"     Circuit Breaker Action:   {BOLD}{RED}⚠️ INTERCEPT TRIGGERED · ESCALATED TO FRAUD COMPLIANCE{RESET}", flush=True)
    else:
        print(f"     Circuit Breaker Action:   {BOLD}{GREEN}✓ PASS (Session Normal · No Intercept Required){RESET}", flush=True)
    print(f"{BOLD}{BLUE}================================================================================{RESET}\n", flush=True)
